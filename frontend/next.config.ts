import type { NextConfig } from 'next';

/**
 * The Laravel application, as this process reaches it.
 *
 * Server-side only. The browser never sees this address — every request a
 * browser makes goes to Next, which forwards it on. That is deliberate and is
 * explained under `rewrites` below.
 *
 * The value is normalised because every `destination` below appends a path that
 * already starts with `/`. A copied-from-the-address-bar origin ending in `/`
 * would produce `https://host//api/...`, and Laravel matches no route with a
 * leading double slash — so the whole API 404s while the pages still render,
 * which reads as a routing bug rather than a configuration one. Blank is treated
 * as absent for the same reason: a dashboard lets you define a variable and
 * leave it empty, and `??` alone would let `''` through.
 */
const backend = (process.env.LARAVEL_ORIGIN?.trim() || 'http://127.0.0.1:8000').replace(/\/+$/, '');

const nextConfig: NextConfig = {
    reactStrictMode: true,

    /**
     * Hostnames the dev server will serve its own assets to.
     *
     * Next's development server refuses cross-origin requests for `/_next/*`
     * and `/__nextjs_font/*` with a bare `403 Unauthorized`. A browser sends an
     * `Origin` header on module scripts and fonts, so reaching this app through
     * any hostname other than the one it is listening on means every chunk is
     * refused -- the HTML renders and the JavaScript never arrives, which in
     * the admin panel looks like it hanging forever on "Checking your session".
     *
     * `curl` does not send `Origin`, which is why the assets appear fine when
     * fetched from a terminal and fail only in the browser.
     *
     * This affects development only; a production build serves static assets
     * without the check.
     */
    allowedDevOrigins: ['50plusvoyagers.test', '*.50plusvoyagers.test'],

    /**
     * Everything Laravel still owns, served through this origin.
     *
     * This is not a convenience. The admin panel authenticates with a Laravel
     * session cookie and a matching `XSRF-TOKEN`, and both are same-origin
     * cookies. If the browser called Laravel on its own port they would be
     * cross-site: the session cookie would need `SameSite=None; Secure`, the
     * CSRF check would need a stateful-domain list, and a signed-in editor
     * would be one browser privacy default away from being signed out. Passing
     * the requests through Next keeps the whole application on one origin, so
     * the cookie rules that already worked keep working unchanged.
     *
     * `/images` and `/storage` come through for a smaller reason: the pictures
     * an editor uploads and the ones shipped with the site live on Laravel's
     * disk, and copying them here would leave two sources of truth for a file.
     */
    async rewrites() {
        return [
            { source: '/api/:path*', destination: `${backend}/api/:path*` },
            { source: '/storage/:path*', destination: `${backend}/storage/:path*` },
            { source: '/images/:path*', destination: `${backend}/images/:path*` },
            { source: '/favicon.ico', destination: `${backend}/favicon.ico` },
            /*
             * `/robots.txt` is deliberately NOT forwarded any more. It is
             * generated by `src/app/robots.ts` in this service instead.
             *
             * Forwarding it meant the crawl rules lived on Laravel's disk while
             * the decision about what is reachable lived in `proxy.ts` here —
             * and the two drifted: the repository's `public/robots.txt` allows
             * everything, but the deployed container answered `Disallow: /`,
             * which removed the entire site from every search index. Nothing in
             * this codebase could show that, because the file being served was
             * not in this codebase.
             */
        ];
    },
};

export default nextConfig;
